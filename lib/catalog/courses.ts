/**
 * Curated course catalog (N8, F8). Version-controlled here, seeded into the
 * `courses` table. Never model-generated, never a live LLM lookup.
 *
 * ── On verified_at ──────────────────────────────────────────────────────────
 * Entries here carry NO verifiedAt. `pnpm seed:catalog` requests every URL and
 * inserts only the ones that resolve, stamping verifiedAt with that run's date.
 * A dead link therefore cannot enter the database at all — which is the failure
 * specs §16.4 says destroys the Learning tab's credibility in one click.
 * `pnpm check:links` re-runs the same check quarterly against what's already in.
 *
 * ── ★ Skill order is load-bearing ───────────────────────────────────────────
 * `skills[0]` is what the entry TEACHES. Everything after it is what the entry
 * is USEFUL TO. `["Redux", "React"]` means a Redux tutorial React people want,
 * not a React tutorial.
 *
 * The course matcher (match.ts) treats the list as flat and is right to — it
 * answers "show me courses for React". The learning engine reads the order,
 * because it answers "what should I study to close a React gap", and those are
 * different questions. Put the taught skill first on every new entry.
 *
 * ── Selection rules ─────────────────────────────────────────────────────────
 * Free-first. Official vendor documentation and roadmap.sh tracks preferred,
 * because they outlive individual creators' channels. Paid entries only where
 * no credible free path exists, and always labelled as paid.
 */

import type { ResourceType } from "./quality";

export interface CourseDef {
  provider: string;
  title: string;
  url: string;
  priceLabel: string;
  lengthLabel: string;
  lengthMinutes: number;
  level: "beginner" | "intermediate" | "advanced";
  /** Two-letter provider mark shown on the card. */
  mark: string;
  isFree: boolean;
  /** Canonical skill names from lib/catalog/skills.ts. Seeding fails on a typo. */
  skills: string[];
  /** Explicit resource type. Wins over the URL heuristic in `typeOf`. */
  type?: ResourceType;
  /** Required on `doc` entries (CHECK in the database): vendor's own docs vs a third party's tutorial. */
  docKind?: "official" | "tutorial";
  /** A survey of a field rather than a lesson in one skill. */
  isOverview?: boolean;
  /** Channel or author as the host reports it (YouTube: oEmbed `author_name`). Verified by `pnpm check:catalog`. */
  author?: string;
}

